// Rule-to-test traceability (D-10, CP-01): reads the product rules in force from the compliance
// register and the rule IDs at the start of test names, and writes docs/traceability.md.
// With --check it fails when a rule in force has no test or the file is out of date.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const register = readFileSync(path.join(root, 'docs/03-compliance-register.md'), 'utf8');

interface Rule { id: string; text: string }
const rules: Rule[] = [];
for (const line of register.split('\n')) {
  const m = /^\| (LB-\d\d) \| (.+?) \|/.exec(line);
  if (!m) continue;
  const text = m[2]!.trim();
  // Rules moved to customer procedures or dropped (D-08, D-09) have no product test.
  if (/^\*(Moved|Dropped)/.test(text)) continue;
  rules.push({ id: m[1]!, text });
}

const tests = new Map<string, string[]>();
const testDir = path.join(root, 'test');
for (const file of readdirSync(testDir).filter((f) => f.endsWith('.test.ts')).sort()) {
  const src = readFileSync(path.join(testDir, file), 'utf8');
  for (const m of src.matchAll(/\bit\(\s*(['"`])((?:LB|CP)-\d\d)([\s\S]*?)\1\s*,/g)) {
    const name = `${m[2]}${m[3]}`.replace(/\\'/g, "'").replace(/\$\{[^}]*\}/g, '…');
    tests.set(m[2]!, [...(tests.get(m[2]!) ?? []), `${file}: ${name}`]);
  }
}

const short = (t: string) => (t.length > 110 ? `${t.slice(0, 107)}…` : t);
const lines = [
  '# Traceability: compliance rules → tests',
  '',
  'Generated by `npm run traceability` from `docs/03-compliance-register.md` and the test names in `test/`.',
  'Each automated test that proves a rule starts its name with the rule ID. Together with the CI test report',
  'this is the validation support for the product rules (D-10, CP-01). Do not edit by hand.',
  '',
  '| Rule | Requirement | Tests |',
  '|------|-------------|-------|',
  ...rules.map((r) => {
    const list = tests.get(r.id) ?? [];
    return `| ${r.id} | ${short(r.text).replaceAll('|', '/')} | ${list.length ? list.map((x) => x.replaceAll('|', '/')).join('<br>') : '**NONE**'} |`;
  }),
  '',
  `${rules.length} rules in force, ${rules.filter((r) => tests.has(r.id)).length} with tests, ${[...tests.values()].flat().length} rule tests.`,
  '',
];
const out = lines.join('\n');
const target = path.join(root, 'docs/traceability.md');

if (process.argv.includes('--check')) {
  const missing = rules.filter((r) => !tests.has(r.id)).map((r) => r.id);
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    // missing file is reported below
  }
  if (missing.length) console.error(`Rules without tests: ${missing.join(', ')}`);
  if (current !== out) console.error('docs/traceability.md is out of date: run npm run traceability');
  process.exit(missing.length || current !== out ? 1 : 0);
}
writeFileSync(target, out);
console.log(`wrote docs/traceability.md: ${rules.length} rules, ${rules.filter((r) => tests.has(r.id)).length} covered`);
